CREATE TABLE public.alimentos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  taco_id INTEGER NOT NULL UNIQUE,
  descricao TEXT NOT NULL,
  categoria TEXT NOT NULL,

  -- Energia e composição geral (valores numéricos da fonte TACO).
  energia_kcal NUMERIC,
  energia_kj NUMERIC,
  umidade_percentual NUMERIC,
  proteina_g NUMERIC,
  lipidios_g NUMERIC,
  colesterol_mg NUMERIC,
  carboidratos_g NUMERIC,
  fibras_g NUMERIC,
  cinzas_g NUMERIC,

  -- Minerais.
  calcio_mg NUMERIC,
  magnesio_mg NUMERIC,
  manganes_mg NUMERIC,
  fosforo_mg NUMERIC,
  ferro_mg NUMERIC,
  sodio_mg NUMERIC,
  potassio_mg NUMERIC,
  cobre_mg NUMERIC,
  zinco_mg NUMERIC,

  -- Vitaminas e equivalentes de retinol.
  retinol_mcg NUMERIC,
  equivalentes_retinol_mcg NUMERIC,
  equivalentes_atividade_retinol_mcg NUMERIC,
  tiamina_mg NUMERIC,
  riboflavina_mg NUMERIC,
  piridoxina_mg NUMERIC,
  niacina_mg NUMERIC,
  vitamina_c_mg NUMERIC,

  -- Ácidos graxos totais e individuais; a notação numérica identifica a cadeia.
  acidos_graxos_saturados_g NUMERIC,
  acidos_graxos_monoinsaturados_g NUMERIC,
  acidos_graxos_poliinsaturados_g NUMERIC,
  acido_graxo_12_0_g NUMERIC,
  acido_graxo_14_0_g NUMERIC,
  acido_graxo_14_1_g NUMERIC,
  acido_graxo_16_0_g NUMERIC,
  acido_graxo_16_1_g NUMERIC,
  acido_graxo_18_0_g NUMERIC,
  acido_graxo_18_1_g NUMERIC,
  acido_graxo_20_0_g NUMERIC,
  acido_graxo_20_1_g NUMERIC,
  acido_graxo_18_2_n_6_g NUMERIC,
  acido_graxo_18_3_n_3_g NUMERIC,
  acido_graxo_20_4_g NUMERIC,
  acido_graxo_20_5_g NUMERIC,
  acido_graxo_22_0_g NUMERIC,
  acido_graxo_22_5_g NUMERIC,
  acido_graxo_22_6_g NUMERIC,
  acido_graxo_24_0_g NUMERIC,
  acido_graxo_18_1_trans_g NUMERIC,
  acido_graxo_18_2_trans_g NUMERIC,

  -- Aminoácidos.
  alanina_g NUMERIC,
  arginina_g NUMERIC,
  acido_aspartico_g NUMERIC,
  cistina_g NUMERIC,
  acido_glutamico_g NUMERIC,
  glicina_g NUMERIC,
  histidina_g NUMERIC,
  isoleucina_g NUMERIC,
  leucina_g NUMERIC,
  lisina_g NUMERIC,
  metionina_g NUMERIC,
  fenilalanina_g NUMERIC,
  prolina_g NUMERIC,
  serina_g NUMERIC,
  treonina_g NUMERIC,
  triptofano_g NUMERIC,
  tirosina_g NUMERIC,
  valina_g NUMERIC,

  dados_origem JSONB NOT NULL
);

COMMENT ON TABLE public.alimentos IS
  'Composição nutricional dos alimentos baseada nos registros da fonte TACO.';

COMMENT ON COLUMN public.alimentos.taco_id IS
  'Identificador original do alimento na base TACO; preserva o ID da fonte.';

COMMENT ON COLUMN public.alimentos.dados_origem IS
  'Registro bruto original do TACO.json, preservado para auditoria e para manter valores especiais da fonte.';

COMMENT ON COLUMN public.alimentos.energia_kcal IS
  'Valor nutricional de energia em kcal conforme fornecido pela fonte TACO.';

COMMENT ON COLUMN public.alimentos.proteina_g IS
  'Valor nutricional de proteínas em gramas conforme fornecido pela fonte TACO.';

CREATE INDEX idx_alimentos_categoria ON public.alimentos (categoria);
